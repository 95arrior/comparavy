// WP 카테고리 자동 선별 회귀 — 유저가 실물로 잡은 오분류를 영구 케이스로 둔다.
//   node --import tsx scripts/check-wp-category.mjs
import { wpCategoryFor } from "../lib/wpCategory.ts";
let fail = 0;
const cases = [
  // ★2026-07-31 실측: '2차전지주'가 생활정보로 빠졌다. 같은 날 '원자력관련주'는 제목에 '종목'이 있어 통과 —
  //  규칙이 아니라 표현이 갈랐다. 섹터+주 표기 자체를 잡는다.
  ["2차전지주", "2차전지주, 지금 들어가도 되는지 판단하는 법", "투자·재테크"],
  ["원자력관련주", "원자력관련주: 지금 담을 만한 종목과 판단 기준", "투자·재테크"],
  ["반도체주 전망", "반도체주는 지금 어떤가", "투자·재테크"],
  ["은행주 배당", "은행주 배당 언제 받나", "투자·재테크"],
  // ★오검출 방지 — '전기차 주행거리'가 '전기차 주'로 걸리면 안 된다
  ["전기차 주행거리", "전기차 주행거리 늘리는 법", "생활정보"],
  // ★2026-07-31 실측: '긴급생계비 지원'이 생활정보로 샜다('지원금'은 있는데 '생계비'가 없었다).
  //  이 오분류가 관련글까지 오염시켰다 — 2차전지주 글 아래에 긴급생계비가 붙었다.
  ["긴급생계비", "긴급생계비 지원, 신청 자격부터 서류까지", "정부지원금"],
  // 기존 규칙 회귀(우선순위가 뒤집히지 않는지)
  ["정기예금특판", "정기예금 특판 찾는 법", "예금·금리"],
  ["주택담보대출 한도", "주담대 한도 계산", "대출·신용"],
  ["IRP 이전", "IRP 계좌이전 방법", "연금·노후준비"],
  ["소상공인정책자금", "소상공인 정책자금 직접대출", "정부지원금"],
  ["중국ETF 세금", "중국ETF 세금까지 정리", "투자·재테크"],
];
for (const [kw, title, want] of cases) {
  const got = wpCategoryFor(kw, title);
  const ok = got === want;
  if (!ok) fail++;
  console.log(ok ? "OK " : "FAIL", kw.padEnd(18), "→", got, ok ? "" : `(기대 ${want})`);
}
console.log(fail === 0 ? "\n통과: 카테고리 매핑" : `\n실패: ${fail}건`);
process.exit(fail ? 1 : 0);
