import { staleFutureDates, scanFacts } from "../lib/factGate.ts";
import { formatBody } from "../lib/publishHtml.ts";
import { RATES } from "../lib/financeCalc.ts";


// ★2026-08-02 유저 실측 — 발행 본문에 이게 그대로 찍혀 나왔다:
//   "[이미지 2 — 여기에 삽입] 표현: 비교 | 은행 예금자보호 한도 변경 |
//    기존 한도=5,000만 원 2. 1억 원, 시행일=2025년 9월 1일 3. 현"
//  두 가지가 겹쳤다:
//   ① 카드가 생성되지 않은 슬롯을 '사진 자리표시자'로 렌더해 라벨=값 원문이 독자에게 노출됐다.
//      카드는 코드가 자동 생성하는 자리라, 안 만들어졌으면 사람이 대신 넣을 것이 없다 —
//      '여기에 삽입하세요'는 사진에만 맞는 안내다.
//   ② 2025년 9월 1일 시행을 '앞으로 바뀔 일'처럼 실었다. 지금은 시행 11개월째다.
let fail = 0;
const ok = (c, l, e = "") => { if (!c) fail++; console.log(c ? "OK " : "FAIL", "|", l, e); };
const NOW = new Date("2026-08-02T00:00:00Z");

// ── ① 봉인된 카드 마커가 발행본에 안 나오는가 ──────────────────────────
{
  const html = "<p>본문 하나.</p><p>[카드: 비교 | 은행 예금자보호 한도 변경 | 기존 한도=5,000만 원 | 1억 원]</p><p>본문 둘.</p>";
  const out = formatBody({ title: "예금자보호 한도", bodyHtml: html, images: {} });
  ok(!/여기에 삽입/.test(out), "★봉인 카드가 자리표시자로 새지 않는다");
  ok(!/표현:/.test(out), "★카드 원문 스펙이 발행본에 없다");
  ok(!/기존 한도=/.test(out), "★'라벨=값' 원문이 발행본에 없다");
  ok(/본문 하나/.test(out) && /본문 둘/.test(out), "주변 본문은 멀쩡하다");

  // 사진 슬롯은 종전대로 자리표시자를 남긴다(유저가 에디터에서 채우는 흐름 — 없애면 안 된다)
  const p = formatBody({ title: "t", bodyHtml: "<p>[사진: 창가에 놓인 화분]</p>", images: {} });
  ok(/여기에 삽입/.test(p), "★사진 슬롯 자리표시자는 유지된다(회귀)");

  // ★문서순 인덱스가 밀리면 안 된다 — 카드를 지워도 뒤 사진이 자기 이미지를 받아야 한다
  const mixed = formatBody({
    title: "t",
    bodyHtml: "<p>[사진: 첫 컷]</p><p>[카드: a=1]</p><p>[사진: 셋째 컷]</p>",
    images: { 0: "https://x/0.png", 2: "https://x/2.png" },
  });
  ok(/0\.png/.test(mixed) && /2\.png/.test(mixed), "★카드를 지워도 뒤 슬롯 인덱스가 안 밀린다");
}

// ── ② 지난 날짜를 미래형으로 쓰면 잡히는가 ─────────────────────────────
for (const s of [
  "2025년 9월 1일부터 예금자보호 한도가 1억 원으로 상향됩니다.",
  "2025년 9월 1일부터 적용됩니다.",
  "앞으로 2024년 7월 제도가 바뀝니다.",
])
  ok(staleFutureDates(s, NOW).length === 1, "★지난 날짜 + 미래형 검거", s.slice(0, 34));

// ── ③ 오탐이 없는가 ────────────────────────────────────────────────────
for (const s of [
  "2025년 9월 1일부터 시행돼 지금 적용 중입니다.",          // 현재 시제 — 정답
  "2026년 12월 1일부터 시행됩니다.",                        // 진짜 미래
  "2025년 9월 1일에 한도가 1억 원으로 올랐습니다.",          // 과거형
  "2026년 7월 20일부터 적용됩니다.",                        // 유예 45일 안 — 막 시행
  "예금자보호 한도는 1억 원입니다.",                         // 날짜 없음
])
  ok(staleFutureDates(s, NOW).length === 0, "오탐 없음", s.slice(0, 34));

// ── ④ 예금자보호 사실 사전이 현행인가 ──────────────────────────────────
//  ★2026-08-02 웹 재확인: 1억 원 상향은 2025년 9월 1일 시행, 지금 적용 중.
{
  const d = RATES.depositProtect;
  ok(d.limit === 100_000_000, "한도 1억 원", String(d.limit));
  ok(d.prev === 50_000_000, "종전 5천만 원");
  ok(d.since === "2025년 9월 1일", "시행일 2025-09-01", d.since);

  const bad = scanFacts("예금자보호 한도는 5,000만 원까지입니다.", "예금자보호");
  ok(bad.some((i) => /5천만/.test(i.title)), "★옛 한도(5천만)를 쓰면 차단");

  const good = scanFacts("기존 5,000만 원에서 1억 원으로 상향됐습니다.", "예금자보호");
  ok(!good.some((i) => /5천만/.test(i.title)), "★'기존 →' 비교 서술은 통과");
}

console.log(fail ? `\n실패 ${fail}건` : "\n통과: 낡은 프레이밍 · 봉인 카드 누출");
process.exit(fail ? 1 : 0);
