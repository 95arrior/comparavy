export interface ArticlePromptInput {
  /** 발행 채널 — 기본 naver(무변경), wordpress면 구글 모드 v2 */
  channel?: "naver" | "wordpress";
  keyword: string;
  angle?: string;
  type: string;
  tone: string;
  /** 목표 글자수 (한국어 기준) */
  maxWords: number;
  /** 구조 다양성 지침 (P1-C — 매번 다른 글이 되도록 생성 전에 주입) */
  variantInstruction?: string;
  /** 업종 — medical | academy | professional | b2b | general(또는 미지정=현행). 전문업종일 때만 추가 지침 주입. */
  vertical?: string;
  /** 업장명(선택) — 글 마무리에서 자연스럽게 연결할 때만 사용. */
  bizName?: string | null;
  /** 운영자가 입력한 강점·특징(선택) — 이 범위 안에서만 언급, 과장은 순화. */
  bizStrength?: string | null;
  // (채널 개념 제거 — 네이버 단일. 모든 글은 네이버 블로그 규격으로 생성)
  /** 사장님이 직접 쓴 '내 이야기'(교재·수업·경험·강점 등, 두서없어도 OK) — 있으면 글의 핵심 재료로 삼아 우리 품질로 재구성. */
  userStory?: string | null;
  /** 사장님이 직접 정한 제목 — 있으면 이 제목을 그대로 쓰고, 본문이 제목과 어긋나지 않게 작성. */
  userTitle?: string | null;
  /** ★계정별 스타일 페르소나(lib/stylePersona) — 같은 계정은 항상 같은 스타일, 계정 간은 다르게(1만 계정 지문 방지). 유저 프롬프트에 주입(캐싱 보존). */
  styleInstruction?: string | null;
  /** ★네이버 자동완성 실데이터 — 검색자들이 실제로 함께 찾는 검색어(관련 질문 점령을 추측→실데이터로). */
  relatedQueries?: string[] | null;
  /** ★오늘 이슈 글감 — 최신 뉴스 발췌(근거 자료). 모델 지식보다 최신인 사실관계의 근거. */
  newsContext?: string | null;
  serpContext?: string | null; // ★SERP 역분석 — 현재 상위 글 제목·요약(능가 브리프)
  relatedPosts?: { title: string; url: string }[] | null; // ★내부링크 — 같은 클러스터 기발행 글(스파이크→에버그린 배관)
  angleBrief?: string | null; // ★C단계 앵글 브리프(방향·구조·톤·독자·훅) — 무중복 증식
  sourceHint?: string | null; // ★근거 한 줄 — 씨앗 메타 출처(기관·매체). 있을 때만 근거 문장 1회.
  affiliate?: boolean | null; // ★리뷰/제휴형 — 대가성 문구 상단 + 상품 링크 자리 마커
}

