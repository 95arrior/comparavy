// ★트래픽 풀 스코어(2026-07-09 유저 회의 확정) — 글감 가치 = 품질 × 잠재 독자 풀 크기.
//  "지방 7세대 무순위(풀=동네 몇백 명)와 동탄 줍줍(풀=전국 시세차익 관심층)은 같은 청약이 아니다."
//  실측 검색량은 '이미 검색되는 것'만 본다 — 공고 직후 폭발할 잠재 풀은 이 프록시가 앞단에서 추정한다.

// 수도권 인기지(시세차익 기대 = 전국 풀) — 유저 시장 감각으로 추가·삭제 (초안: 로또 청약 단골 지역)
export const HOT_REGIONS = [
  "동탄", "과천", "하남", "위례", "판교", "광명", "분당", "성남", "송파", "강남", "서초", "강동",
  "마포", "용산", "성동", "고양", "창릉", "김포", "검단", "평촌", "산본", "의왕", "군포", "안양",
  "수원", "광교", "용인", "화성", "인천 송도", "송도", "청라", "마곡", "둔촌", "개포",
];
const METRO = ["서울", "부산", "대구", "인천", "광주", "대전", "울산", "세종"];

/** 지역 등급 — 3: 수도권 인기지·서울 / 2: 광역시·경기 주요 / 1: 기타 시 / 0: 군·소도시 */
export function regionTier(text: string): 0 | 1 | 2 | 3 {
  if (HOT_REGIONS.some((r) => text.includes(r))) return 3;
  if (METRO.some((r) => text.includes(r))) return 2;
  if (/경기|성남|부천|안산|남양주|의정부|파주|시흥|구리|광주시/.test(text)) return 2;
  if (/[가-힣]{1,4}군(?![가-힣])/.test(text)) return 0;
  return 1;
}

// 대상 인구 크기 — 전 국민급 주제(누구나 걸리는 돈) vs 대규모 집단 vs 소수
const UNIVERSAL = /(재산세|자동차세|종합소득세|연말정산|국민연금|건강보험|전기요금|가스요금|근로장려금|자녀장려금|기준금리|예금자보호|월세|전세|대출 ?금리|유가|환율|기름값|통신비|증여세|상속세)/;
const BIG_GROUP = /(직장인|부모|맞벌이|신혼|세입자|임차인|1인 ?가구|자영업|소상공인|은퇴|주부|청년|무주택|출산|육아|임산부|임신|아이 ?키우|퇴직)/;

/** 풀 스코어 0~8 — 카드·씨앗 공통(텍스트에 지역·대상 신호가 있으면 반영) */
export function poolScore(text: string): number {
  let sc = 0;
  if (UNIVERSAL.test(text)) sc += 3;
  else if (BIG_GROUP.test(text)) sc += 2;
  // 청약 로또 프레임 — 무순위/줍줍 × 인기지 = 전국 풀(줍줍 단독 표현도 청약 문맥으로 간주)
  const tier = regionTier(text);
  if (/(무순위|줍줍|잔여 ?세대|취소분)/.test(text)) sc += tier >= 3 ? 5 : tier === 2 ? 2 : 0; // 인기지 줍줍 = 그 자체로 로또 프레임(전국 풀)
  else if (/청약|분양/.test(text)) sc += tier >= 3 ? 2 : tier === 2 ? 1 : 0;
  if (/(분양가 ?상한|시세 ?차익|반값)/.test(text)) sc += 2;
  // 지역이 명시된 비청약 글감(지원금 등)은 지역 풀을 따른다 — 군 단위는 감점
  if (!/청약|분양/.test(text) && /[가-힣]{2,4}(시|군|도)\s/.test(text)) sc += tier - 1; // tier0(군)=-1, tier3=+2
  return Math.max(0, Math.min(8, sc));
}

/** 대형 글감 판정 — 보드에서 강조할 임계 */
export function isBigPool(text: string): boolean {
  return poolScore(text) >= 5;
}
