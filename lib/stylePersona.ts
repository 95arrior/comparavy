//       해시는 '충돌 확률이 낮다'일 뿐 0이 아니고, 두 계정이 같은 스타일을 받으면 그게 곧 지문이다.
//       프리셋은 사람이 설계하므로 각각을 '네이버가 좋아하는가'로 개별 검증할 수 있다(해시 조합은 검증 불가).
//   (2) 축이 표면에서 문체로 내려갔다. 기존 7축(도입 형식·형광 위치·마무리·해시태그 개수·소제목형·호흡·이모지)은
//       전부 '겉모습'이라 두 글을 나란히 놓으면 같은 사람이 쓴 티가 났다 — 어미·인칭·수치 화법이 같았기 때문이다.
//       그래서 어미 체계·1인칭 호칭·수치 화법·도입 온도를 축으로 추가했다.
//   ★불변: 같은 계정 = 항상 같은 스타일(C-Rank는 블로그 내 일관성을 좋아한다). 계정 간 = 서로 다름.
//   ★불변: 시스템 프롬프트가 아니라 '유저 프롬프트'에 주입한다(프롬프트 캐싱 공유 프리픽스를 깨지 않는다 — 비용 증가 0).

// FNV-1a 32bit — 의존성 없는 결정적 해시(11번째 계정부터의 폴백 배정에만 쓴다)
function fnv1a(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

