/**
 * ★배정 원장 — 블로그(또는 유저) id → 프리셋 인덱스.
 *  환경변수 ATEFLO_STYLE_ASSIGN에 "id:P3,id2:P7" 형태로 적어 고정 배정할 수 있다(운영 중 스타일 교체용).
 *  적지 않으면 아래 stablePresetIndex가 해시로 배정한다 — 10석 안에서는 실제로 겹칠 수 있으므로
 *  ★10명 운영을 시작하면 이 환경변수로 1:1 고정하는 것이 설계 의도다(그때 충돌 0이 보장된다).
 */
function assignedFromEnv(seedId: string): StylePreset | null {
  const raw = process.env.ATEFLO_STYLE_ASSIGN;
  if (!raw) return null;
  for (const pair of raw.split(",")) {
    const [id, key] = pair.split(":").map((x) => x.trim());
    if (id && key && id === seedId) return STYLE_PRESETS.find((p) => p.key === key) ?? null;
  }
  return null;
}

function stablePresetIndex(seedId: string): number {
  return fnv1a(`${seedId}|preset`) % STYLE_PRESETS.length;
}

/** 이 계정(블로그)의 스타일 프리셋. 같은 id는 언제나 같은 프리셋을 돌려준다. */
export function stylePresetFor(seedId: string): StylePreset {
  return assignedFromEnv(seedId) ?? STYLE_PRESETS[stablePresetIndex(seedId)]!;
}

/** 유저별 고정 스타일 지시문. 같은 seedId는 언제나 같은 문자열을 돌려준다. */
export function stylePersonaInstruction(seedId: string): string {
  return stylePresetFor(seedId).traits.join(" · ");
}
