    let arr: unknown[] = [];
    if (m) {
      try { arr = JSON.parse(m[0]) as unknown[]; }
      catch {
        const objs = m[0].match(/\{[^{}]*\}/g) ?? [];
        arr = objs.map((s) => { try { return JSON.parse(s); } catch { return undefined; } });
      }
    }
