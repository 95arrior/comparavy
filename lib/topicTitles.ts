            //  금지한 '이것만 알면'을 그대로 쓰고 있었다. 모델은 규칙보다 예시를 따른다 — 우리 보드에 뜬
            //  '패시브인컴 만드는 기초, 어디서부터 시작할까'가 이 예시의 자식이다. 예시가 곧 규격이다.
            // ★예시를 그대로 베끼는 것도 막는다(2026-08-03 실물에서 검거) — 프롬프트에 넣은 예시
