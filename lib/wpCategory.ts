// ★WP 카테고리 자동 선별(2026-07-12 유저: Uncategorized 방치 금지) — 키워드·제목 기반 규칙 매핑.
//  카테고리는 구글 토픽 클러스터의 뼈대: 소수의 굵은 분류(난립 금지). 매핑 실패 시 '생활정보'.
const RULES: [RegExp, string][] = [
  [/(연금|IRP|퇴직금|퇴직연금|노후|국민연금)/, "연금·노후준비"],
  [/(세액공제|소득공제|연말정산|종합소득세|절세|세금|재산세|종부세|양도세|증여|상속|부가세)/, "세금·연말정산"],
  [/(예금|적금|금리|통장|파킹|CMA|이자|저축)/, "예금·금리"],
  [/(청약|분양|전세|월세|보증금|부동산|주택|아파트|등기)/, "부동산·청약"],
  [/(대출|한도|LTV|DSR|담보|신용점수|금융권)/, "대출·신용"],
  [/(지원금|보조금|장려금|바우처|수당|급여|복지|환급)/, "정부지원금"],
  [/(주식|ETF|펀드|ISA|배당|투자|증권)/, "투자·재테크"],
  [/(보험|실손|보장|청구)/, "보험"],
];

export function wpCategoryFor(keyword: string, title?: string | null): string {
  const text = `${keyword} ${title ?? ""}`;
  for (const [re, name] of RULES) if (re.test(text)) return name;
  return "생활정보";
}
