// ★글감 유형 신호(2026-07-31 실측 — ★컷이 아니라 측정·정렬용). pigtong.com 발행 26편 × 클릭 8회 실측:
//  같은 검색량 구간(340~1,650)에서 행동·판단형 9편은 4편이 클릭을 받았고, 분류·용어형 9편은 전부 0이었다.
//   클릭: 회사채금리 1,240 · 저평가우량주 890 · cma계좌개설 880 · irp이전 400
//   0클릭: 금융기관 1,270 · 코인종류 1,020 · 온투업 700 · 모의주식 510 · 저축은행종류 340 · 보통주 320 · 베트남펀드 350
//  ★차단으로 승격하지 않는다. 표본이 26편·클릭 8회뿐이고, 용어형의 0클릭이 '유형 탓'인지
//   '검색량·경쟁 탓'인지 아직 분리되지 않았다(국내주식 235,500·소상공인정책자금 259,000이 같은 칸에 섞여 있다).
//   수명 컷과 같은 절차를 따른다: 측정 → 표본 축적 → 승격. 여기서 지금 막으면 근거보다 규칙이 앞선다.
/** 행동·수치·조건 신호 — 검색자가 '하러 가기 전' 또는 '따져보는 중'인 말. */
export const ACTION_INTENT_RE = /(개설|이전|신청|접수|가입|해지|발급|변경|비교|계산|얼마|방법|조건|기준(?![가-힣])|특판|금리|수수료|세금|환급|공제|한도|차이|장단점)/;
/** 판단·선별 수식어 — 용어 자체가 아니라 '고르는 기준'을 담은 말(실측: 저평가우량주는 용어형처럼 보이지만 클릭이 났다). */
export const JUDGE_MODIFIER_RE = /(저평가|우량|추천|인기|안전|고금리|최고|유리|절세|숨은)/;

/** 글감 유형 판정 — 차단용이 아니라 관측·정렬용. 짧은 명사 단독이면 '용어'로 본다. */
export function topicIntent(keyword: string): "행동판단" | "용어" | "중립" {
  const k = (keyword ?? "").replace(/\s+/g, "");
  if (!k) return "중립";
  if (ACTION_INTENT_RE.test(k) || JUDGE_MODIFIER_RE.test(k)) return "행동판단";
  if (k.length <= 8 && !/\d/.test(k)) return "용어"; // 수식어도 행동어도 숫자도 없는 짧은 명사 = 분류·용어 자체
  return "중립";
}

// ★요일 축(2026-07-31 실측 — 데이터랩 검색어트렌드 일 단위 90일). 주말 조회수 저조의 원인을 가른 결과다.
//  판정: 블로그가 지는 게 아니라 시장이 빠진다 — 금융 주제 수요 주말/평일 60%, 관측 조회수도 약 65%로 일치.
//   급락: 정기예금 특판 48% · IRP 이전 49% · CMA 계좌개설 65% — 영업일이 있어야 '실행'되는 말
//   완만: 저평가 우량주 75% · 가계부 쓰는 법 75% · 노후 준비 84% — 시간 있을 때 '따져보는' 말
//   대조군: 맛집 163% · 영화 예매 140%(측정이 주말 상승을 실제로 잡아낸다는 확인 — 이게 없으면 60%가 고장인지 모른다)
//  ★감점만 넣고 가점은 넣지 않는다: 금융에서 주말에 '오르는' 주제는 측정상 하나도 없었다(최고가 84%).
//  ★파이 보정도 하지 않는다: 주말 절대 수요는 적금 추천 15.0·연말정산 16.0 vs 노후 준비 1.7로 9배 차이지만,
//   검색량은 이미 별점(filledStarsFromData)에 반영돼 있어 여기서 또 가중하면 이중 계산이 된다.
const BIZDAY_ACTION_RE = /(개설|이전(?![가-힣])|신청|접수|발급|해지|특판|가입|방문|창구|영업일)/;
/**
 * 주말 배정 보정 — 영업일이 있어야 실행되는 글감은 주말에 감점. day: 0=일 … 6=토(★KST 기준으로 넘길 것).
 * 금요일을 포함하는 이유: 네이버는 색인이 빨라 금요일에 쓴 글이 주말 검색을 그대로 받는다(WP와 다른 점).
 */
export function weekendAdjust(keyword: string, day: number): number {
  const weekendish = day === 0 || day === 6 || day === 5;
  if (!weekendish) return 0;
  return BIZDAY_ACTION_RE.test(keyword ?? "") ? -6 : 0;
}

