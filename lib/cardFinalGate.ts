/** 응답 직전 최종 검문 — 통과 카드와 탈락 사유를 함께 반환(관측 가능). */
/**
 * @param opts.anchorKeyword ★홈판 레인 전용(2026-08-02 실측). 홈판 카드의 keyword는 검색 키워드가 아니라
 *  '주제 앵커(소재)'이고, 제목과 앵커가 **같은 LLM 호출에서 함께** 나온다 — 즉 아래 4)가 막으려는
 *  '짝 밀림'(다른 씨앗의 제목이 붙는 조립 오류)이 구조적으로 일어날 수 없는 경로다.
 *  그런데 규칙 4)는 토큰 교집합을 요구하므로 좋은 홈판 제목이 조립 오류로 오인돼 버려졌다:
 *    앵커 "7월 숨은 환급금" ← 제목 "이번 달 월급 들어오기 전에, 먼저 찾아갈 돈이 있습니다" (실측 탈락)
 *  그래서 이 레인에서만 4)를 끈다. 나머지 게이트(지역·폐지제도·수명·안전)는 전부 그대로 적용된다.
 */
export function finalGate<T extends GateCard>(cards: T[], opts?: { anchorKeyword?: boolean }): { pass: T[]; drops: GateDrop[] } {
  const pass: T[] = [];
  const drops: GateDrop[] = [];
  for (const c of cards) {
    const text = `${c.title} ${c.keyword}`;
    // ★엔터 소재 컷(2026-08-14 실측: 영화 '프로젝트 헤일메리 ott 언제'가 황금 점수로 추천됨) —
    //  검색자=영화 팬이지 경제 독자가 아니다(검색자≠손님). 판정은 isEntertainmentTopic 한 곳(머니랭킹도 같은 자를 쓴다).
    if (isEntertainmentTopic(text)) {
      drops.push({ keyword: c.keyword, reason: "entertainment" }); continue;
    }
    // 1) 지역 협소 — 지역명이 박힌 글감은 전국 풀 신호(전국민 주제·인기지 청약 등)가 없으면 부적격.
    //    '서울시 출산가구 720만'(대집단+광역 4점)은 통과, '강서구 평생교육이용권'(0~1점)은 컷.
    // ★폐지·종료 제도 하드컷(2026-08-01 유저 지시 "빡세게") — 실측: '재형저축'(2015년 가입 종료)이
    //  "세금 우대받으며 모으는 방법"으로 글감에 떴다. 검색은 되지만 지금 가입하러 가면 헛걸음한다.
    //  품질이 아니라 독자가 실제로 손해를 보는 오류라 스팸 대출과 같은 급으로 끊는다. 사전은 lib/discontinued 한 곳.
    // ★제목이 제목이 아닌 것(2026-08-02 유저 실측 — 화면에 '대부업체' 한 단어가 카드로 떴다).
    //  키워드를 그대로 놓거나 거기에 '총정리·정리' 한 마디만 붙인 건 제목이 아니라 라벨이다.
    //  클릭할 이유가 없고, 홈판이든 검색이든 이런 건 지나쳐진다.
    //  ★'총정리'류는 유저가 금지한 틀이다(썸네일 카피 금지어와 같은 계열) — 폴백에서도 뺐다.
    {
      const cmp = (x: string) => String(x || "").replace(/\s+/g, "").toLowerCase();
      const bare = cmp(c.title).replace(/[,·.!?]/g, "");
      const kwc = cmp(c.keyword);
      // ★'총정리'를 전면 금지하려다 되돌렸다(2026-08-02) — 유저가 말한 적 없는 내 추론이었고,
      //  '백년가게로 지정되면 받는 혜택 총정리'처럼 내용이 있는 제목까지 죽였다(기존 회귀가 잡아냈다).
      //  진짜 결함은 '총정리'라는 단어가 아니라 '키워드에 그 한 마디만 붙인 라벨'이다.
      const stripped = bare.replace(kwc, "").replace(/^(총정리|완벽정리|핵심정리|정리|모음|안내)$/, "");
      if (kwc && bare.includes(kwc) && stripped.length === 0) {
        drops.push({ keyword: c.keyword, reason: "title_is_label" }); continue;
      }
    }
    { const ep = endedProgramOf(text); if (ep) { drops.push({ keyword: c.keyword, reason: `ended:${ep.name}` }); continue; } }
    if (SCAM_LOAN_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "scam_loan" }); continue; } // 대기업 사칭 대출(삼성재단대출류) — 법적 안전, 양 채널 하드컷
    // ★민간 대출 상품(2026-08-05 유저: "대출추천은 역시 안 돼") — 공적·정책 금융(햇살론·디딤돌 등)은 예외
    { const pl = privateLoanTopic(text); if (pl) { drops.push({ keyword: c.keyword, reason: "loan_product" }); continue; } }
    // ★정답 소비형(퀴즈·룰렛·뽑기) — 관심도가 높아도 체류가 0이라 우리가 먹을 게 없다
    { const co = consumeOnlyTopic(text); if (co) { drops.push({ keyword: c.keyword, reason: `consume_only:${co}` }); continue; } }
    if (SPECULATIVE_RE.test(`${text} ${(c.newsContext ?? "").slice(0, 120)}`)) { drops.push({ keyword: c.keyword, reason: "speculative" }); continue; } // 유령 제도 — 지역 구제보다 먼저
    // ★특정 직업·신분 한정(2026-08-07) — 수요 게이트의 '구제'(풀 스코어)로도 살아나면 안 되는 종류라 최종 관문에 둔다.
    //  실측: 건설근로자공제회가 "풀 3으로 구제"돼 보드에 섰다. 구제는 수요 증거지 대상 폭의 증거가 아니다.
    if (NARROW_AUDIENCE_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "narrow_audience" }); continue; }
    // ★채용은 유명 대기업·공기업(성과급 포모)만(2026-08-07 유저 확정)
    if (RECRUIT_RE.test(text) && !MAJOR_EMPLOYER_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "recruit_minor" }); continue; }
    // ★공시 카드가 공시 얘기를 안 하면 실격(2026-08-07 — 사내카페 실물)
    if (c.seedSource === "dart" && !DART_ACTION_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "dart_lineage" }); continue; }
    if (HARD_B2B_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "b2b-hard" }); continue; }
    // ★기초지자체가 제목 앞머리에 오면 문턱을 올린다(2026-08-02 유저 화면 실측).
    //  통과한 실물: "의정부시 청년 투자환경, 일자리·주거 원스톱 지원 프로그램"
    //  poolScore가 '청년·지원'을 전국민 신호로 보고 +3을 줘서 지역 협소성을 상쇄했다.
    //  ★하지만 그 프로그램은 의정부 청년만 신청한다 — 전국민 주제어가 붙었다고 전국 수요가 되지 않는다.
    //  제목 선두에 지자체명이 오면 '그 지역 전용 글감'이다. 인기지 청약처럼 전국이 쳐다보는
    //  신호(poolScore 5+)가 있을 때만 살린다 — '서울시 출산가구 720만'(3+2=5)은 그대로 통과한다.
    //  ★단, 광역(시·도)과 기초(시·군·구)를 갈라야 한다. 문턱을 일괄로 올렸더니
    //   '서울시 무주택 출산가구 720만원 주거비 지원'과 '서울 전세보증금 반환 절차'가 죽었다(기존 회귀가 잡음).
    //   광역은 전국 인지도가 있어 타지역 사람도 검색한다. 문제는 의정부시·강서구 같은 기초지자체다.
    const head = String(c.title || "").slice(0, 15);
    const headRegion = REGION_RE.test(head) && !WIDE_REGION_RE.test(head);
    const poolMin = headRegion ? 5 : 3;
    if ((REGION_RE.test(text) || LOCAL_CURRENCY_RE.test(text)) && poolScore(`${text} ${(c.newsContext ?? "").slice(0, 200)}`) < poolMin) {
      drops.push({ keyword: c.keyword, reason: "region_niche" });
      continue;
    }
    // 1.5) 정답형 도구(계산기) — 공식 위젯 잠식 유형, 블로그 자리 자체가 없다
    if (ANSWER_TOOL_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "answer_tool" }); continue; }
    // 1.6) AI 브리핑 한 줄 종결형(정의) — 케이스 분기 신호 없으면 AI 요약으로 끝나 클릭이 남지 않는 자리
    if (AI_DEFINITION_RE.test(c.keyword) && !CASE_BRANCH_RE.test(c.keyword)) { drops.push({ keyword: c.keyword, reason: "ai_one_liner" }); continue; }
    // 1.7) 보고서체 제목(2026-07-20 실측) — 뉴스 원제 폴백 노출 차단: 사람이 클릭할 훅이 없는 논문 목차형
    if (REPORT_TONE_RE.test(c.title) && !HOOK_SIGNAL_RE.test(c.title)) { drops.push({ keyword: c.keyword, reason: "report_tone" }); continue; }
    // 2) 죽은 공고·행사(행동 창 닫힘)
    if (DEAD_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "dead_event" }); continue; }
    // 3) 읽고 끝나는 뉴스성
    if (NEWSY_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "newsy" }); continue; }
    // 3.4) 정치·역사 갈등 민감 주제 — 법적 안전·계정 지속 원칙(정치색은 어느 쪽이든 절반의 독자를 적으로)
    if (SENSITIVE_RE.test(text)) { drops.push({ keyword: c.keyword, reason: "sensitive" }); continue; }
    // 3.5) B2B 지원사업(실측 2026-07-10: '식품 기업 최대 1360만원 정부지원금' — 독자=기업 담당자 소수).
    //     수확기(기업마당)엔 독자 게이트가 있지만 뉴스 증식 경로가 무검문이었다 — 관문에서 일괄 차단.
    if (B2B_RE.test(text) && !B2C_SIGNAL_RE.test(`${text} ${(c.newsContext ?? "").slice(0, 200)}`)) {
      drops.push({ keyword: c.keyword, reason: "b2b_audience" });
      continue;
    }
    // 3.9) ★수명 컷(체인 마지막 — 기존 사유가 더 구체적이라 먼저 잡게 두고, 아무것도 안 걸린 것만 여기서)(2026-07-29 실측 측정 후 승격) — 날짜·회차가 박힌 글감은 그 시점이 지나면 같이 죽는다.
    //  근거: 루원시티 SK 청약(7월 13일 마감) 주간 조회 91 → 8, 경남 2차 추경 7. 트렌드 글감의 15.8%가 여기 해당.
    //  측정으로 확인한 안전선: 내 발행 글 기준 9%, 트렌드 95개 중 15개 제외(80개 남음) — 발행 지속에 지장 없음.
    //  검색량 임계는 추가하지 않는다 — 밴드 사다리(TIER_BANDS)가 이미 통제 중이라 이중으로 조이면 신생 밴드와 충돌한다.
    { const life = scanLifespan(c.keyword, c.title, null, 0);
      // ★수명 컷의 예외(2026-08-05 실측: '법인세 중간예납, 8월 31일까지 해야 하는 것'이 잘렸다).
      //  이 규칙은 '마감이 지나면 죽는 글감'을 막으려고 만든 것이다(루원시티 청약 91 → 8).
      //  그런데 캘린더·정부발표 원천은 '아직 안 온 마감을 미리 잡는 것'이 존재 이유다 —
      //  ★막으려던 것과 정반대인 글감을, 같은 규칙이 자르고 있었다.
      //  갈림: 마감이 아직 안 지났으면 지금이 그 글감의 전성기다. 지난 마감만 죽는다.
      const aEnd = (c.actionEnd ?? "").trim();
      const futureDeadline = /^\d{4}-\d{2}-\d{2}$/.test(aEnd)
        && Date.parse(`${aEnd}T23:59:59+09:00`) >= Date.now();
      // ★마감을 아는 카드는 마감으로만 판정한다 — 원천을 이유로 지난 마감까지 봐주면 안 된다.
      //  마감을 모르는 캘린더·정부발표 카드만 원천으로 구제한다(그 원천은 아직 안 온 일정만 낸다).
      const datedBySource = !aEnd && (c.seedSource === "calendar" || c.seedSource === "gov");
      const exemptDated = aEnd ? futureDeadline : datedBySource;
      if (life.reasons.includes("dated") && !exemptDated) { drops.push({ keyword: c.keyword, reason: "dated_topic" }); continue; }
      // ★차수도 같은 예외를 받는다(2026-08-05 실측: '더 리치먼드 미아(2차) 무순위 청약'이 잘렸다).
      //  이 규칙은 '그 회차가 끝나면 죽는 글감'을 막으려는 것이다(경남 2차 추경 주 7회).
      //  ★그런데 무순위·특별공급 청약은 차수가 붙는 게 정상이고, 접수가 아직 안 끝났으면
      //   지금이 그 글감의 전성기다 — dated와 정확히 같은 구조인데 예외만 빠져 있었다.
      if (life.reasons.includes("round") && !exemptDated) { drops.push({ keyword: c.keyword, reason: "round_topic" }); continue; } }
    // 4) 제목-키워드 정합(짝 밀림류 최후 방어) — 실질 토큰 교집합 0이면 조립 오류로 간주
    //    ★앵커 레인(홈판)은 이 검사를 건너뛴다 — 위 opts.anchorKeyword 주석 참조.
    if (opts?.anchorKeyword) { pass.push(c); continue; }
    const toks = (t: string) => new Set(t.replace(/[^가-힣a-zA-Z0-9 ]/g, " ").split(/\s+/).filter((w) => w.length >= 2));
    const kt = toks(c.keyword), tt = toks(c.title);
    const overlap = [...kt].some((w) => tt.has(w) || [...tt].some((x) => x.includes(w) || w.includes(x)));
    if (kt.size > 0 && tt.size > 0 && !overlap) { drops.push({ keyword: c.keyword, reason: "title_keyword_mismatch" }); continue; }
    pass.push(c);
  }
  return { pass, drops };
}

/** ★낡은 연도 정정(2026-08-14 유저 실측: '비거주 1주택자 전세대출 제한 2025' — 뉴스는 올해 건인데 모델이 학습 시절 연도를 붙임).
 *  지금 뜨는 뉴스에서 나온 글감의 과거 연도는 오타다 — 올해로 고친다. 올해·미래 연도는 그대로(선행 발행 전략).
 *  예외: 1월엔 작년 표기가 정당할 수 있다(연말정산 귀속 등) — 그때만 작년을 살려둔다. */
/** ★엔터 소재 판정 — 작품 자체면 true, 구독료·요금 같은 돈 각도는 false(2026-08-17 머니랭킹과 공유). */
export function isEntertainmentTopic(text: string): boolean {
  const t = String(text ?? "");
  return /(ott|넷플릭스|디즈니플러스|티빙|웨이브|쿠팡플레이)\s*(언제|공개|출시|방영)|영화|드라마|개봉|웹툰|아이돌|콘서트|팬미팅|흥행|관객수/i.test(t)
    && !/(요금|구독료|가격|인상|할인|환불|투자|매출|주가)/.test(t);
}

export function normalizeStaleYear(text: string, now: Date = new Date(Date.now() + 9 * 3600_000)): string {
  const y = now.getFullYear();
  return String(text ?? "").replace(/(20\d{2})(년?)/g, (m, yr: string, suffix: string) => {
    const n = Number(yr);
    if (n >= y) return m;
    if (n === y - 1 && now.getMonth() === 0) return m;
    return `${y}${suffix}`;
  });
}
