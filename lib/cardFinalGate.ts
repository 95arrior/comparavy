export function weekendAdjust(keyword: string, day: number): number {
  const weekendish = day === 0 || day === 6 || day === 5;
  if (!weekendish) return 0;
  return BIZDAY_ACTION_RE.test(keyword ?? "") ? -6 : 0;
}

